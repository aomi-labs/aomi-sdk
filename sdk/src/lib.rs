//! # aomi-sdk
//!
//! The guest SDK for Aomi packages. A package is a WebAssembly component for
//! the `aomi:package@1.0.0` world (contract version 1), built for
//! `wasm32-wasip2`. The backend loads it into a sandbox and calls its tools.
//!
//! ```rust,ignore
//! use aomi_sdk::{Ctx, Outcome, Result, Tool, http};
//!
//! #[derive(serde::Deserialize, schemars::JsonSchema)]
//! pub struct PriceArgs { coins: String }
//!
//! pub struct Price;
//! impl Tool for Price {
//!     const NAME: &'static str = "price";
//!     const DESCRIPTION: &'static str = "Current USD price of coins.";
//!     type Args = PriceArgs;
//!     async fn run(args: PriceArgs, _ctx: &Ctx) -> Result<Outcome> {
//!         let url = format!("https://coins.llama.fi/prices/current/{}", args.coins);
//!         let body: serde_json::Value = http::get(url).send().await?.json()?;
//!         Ok(Outcome::data(body))
//!     }
//! }
//!
//! aomi_sdk::package!(Price);
//! ```
//!
//! The crate compiles natively too, so tool logic can be unit-tested with
//! `cargo test`; host imports (`http`, `chain`, `secrets`, `log`) panic when
//! called outside the sandbox. [`testing::ctx`] builds a call context.
#![allow(async_fn_in_trait)]

