/// The contract version this SDK implements; `describe()` reports it.
pub const CONTRACT: u32 = 1;

/// A tool result: the outcome, or a package error the model sees as `[code] message`.
pub type Result<T, E = Error> = std::result::Result<T, E>;

/// A package error. `code` is `[a-z0-9_]`, at most 64 bytes.
pub fn err(code: &str, message: impl Into<String>) -> Error {
    Error {
        code: code.into(),
        message: message.into(),
    }
}

impl From<types::HostError> for Error {
    fn from(e: types::HostError) -> Self {
        err(&e.code, e.message)
    }
}

impl From<serde_json::Error> for Error {
    fn from(e: serde_json::Error) -> Self {
        err("invalid_json", e.to_string())
    }
}

#[doc(hidden)]
pub mod __private {
    pub use crate::tool::call;
    pub use wstd::runtime::block_on;
}

/// Exports the listed tools as the package: `describe` reports them and
/// `call-tool` dispatches by short name, runs the tool to completion and maps
/// its result to the WIT types. Use it once per package crate.
#[macro_export]
macro_rules! package {
    ($($tool:ty),+ $(,)?) => {
        /// The package's WIT guest, generated by `aomi_sdk::package!`.
        pub struct AomiPackage;

        impl $crate::bindings::Guest for AomiPackage {
            fn describe() -> $crate::bindings::aomi::package::types::Manifest {
                $crate::bindings::aomi::package::types::Manifest {
                    contract: $crate::CONTRACT,
                    tools: vec![$($crate::bindings::aomi::package::types::ToolDef::of::<$tool>()),+],
                }
            }

            fn call_tool(
                name: String,
                args: String,
                ctx: $crate::Ctx,
            ) -> $crate::Result<$crate::bindings::aomi::package::types::Outcome> {
                $crate::__private::block_on(async move {
                    $(
                        if name == <$tool as $crate::Tool>::NAME {
                            return $crate::__private::call::<$tool>(&args, &ctx).await;
                        }
                    )+
                    Err($crate::err("unknown_tool", format!("no tool named `{name}`")))
                })
            }
        }

        $crate::bindings::export!(AomiPackage with_types_in $crate::bindings);
    };
}
