use super::*;

const SPEC: &str = r#"
openapi: 3.0.3
info: { title: demo, version: "1" }
servers: [{ url: "https://api.demo.test" }]
paths:
  /ping:
    get:
      operationId: ping
      responses:
        "200":
          description: ok
          content:
            application/json:
              schema: { type: object, additionalProperties: true }
"#;

struct Fixture {
    dir: tempfile::TempDir,
}

impl Fixture {
    fn new() -> Self {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(
            dir.path().join("Cargo.toml"),
            "[workspace]\nmembers = [\"packages/*\"]\n\n[workspace.dependencies]\n",
        )
        .unwrap();
        std::fs::create_dir_all(dir.path().join("specs")).unwrap();
        std::fs::write(dir.path().join("specs/demo.yaml"), SPEC).unwrap();
        Self { dir }
    }

    fn path(&self, rel: &str) -> PathBuf {
        self.dir.path().join(rel)
    }

    fn args(&self, check: bool) -> GenClientArgs {
        GenClientArgs {
            platform: "demo".into(),
            spec: Some(self.path("specs/demo.yaml")),
            out: None,
            force: true,
            shared: true,
            check,
            preprocessed: None,
        }
    }

    fn run(&self, check: bool) -> Result<()> {
        run_in(self.dir.path(), self.args(check))
    }

    fn files(&self) -> Vec<PathBuf> {
        let mut out = Vec::new();
        let mut stack = vec![self.dir.path().to_path_buf()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(dir).unwrap() {
                let path = entry.unwrap().path();
                if path.is_dir() {
                    stack.push(path);
                } else {
                    out.push(path);
                }
            }
        }
        out.sort();
        out
    }
}

#[test]
fn shared_run_writes_a_crate_and_wires_the_workspace() {
    let fx = Fixture::new();
    fx.run(false).unwrap();

    let client = std::fs::read_to_string(fx.path("crates/clients/demo/src/client.rs")).unwrap();
    assert!(client.starts_with("// @generated by `aomi-build gen-client` "));
    assert!(client.contains("// spec sha256: "));
    assert!(client.contains("aomi_progenitor_client"));
    assert!(fx.path("crates/clients/demo/src/lib.rs").exists());

    let cargo = std::fs::read_to_string(fx.path("crates/clients/demo/Cargo.toml")).unwrap();
    assert!(cargo.contains("name = \"demo-client\""));
    assert!(cargo.contains("aomi-progenitor-client = { workspace = true }"));
    let root = std::fs::read_to_string(fx.path("Cargo.toml")).unwrap();
    assert!(root.contains("\"crates/clients/*\""));
    assert!(root.contains("aomi-progenitor-client = { git = "));
}

#[test]
fn check_passes_when_current_and_fails_on_client_drift() {
    let fx = Fixture::new();
    fx.run(false).unwrap();
    fx.run(true).unwrap();

    let client = fx.path("crates/clients/demo/src/client.rs");
    let edited = format!(
        "{}// hand edit\n",
        std::fs::read_to_string(&client).unwrap()
    );
    std::fs::write(&client, &edited).unwrap();
    let err = fx.run(true).unwrap_err().to_string();
    assert!(err.contains("out of date"), "{err}");
    assert_eq!(std::fs::read_to_string(&client).unwrap(), edited);
}

#[test]
fn check_fails_when_the_spec_changed() {
    let fx = Fixture::new();
    fx.run(false).unwrap();
    std::fs::write(fx.path("specs/demo.yaml"), SPEC.replace("ping", "pong")).unwrap();
    assert!(fx.run(true).is_err());
}

#[test]
fn check_writes_nothing() {
    let fx = Fixture::new();
    let before = fx.files();
    assert!(fx.run(true).is_err());
    assert_eq!(fx.files(), before);
}

#[test]
fn preprocessed_spec_is_written_only_where_asked() {
    let fx = Fixture::new();
    fx.run(false).unwrap();
    assert!(!fx.path("specs/demo.preprocessed.yaml").exists());

    let mut args = fx.args(false);
    args.preprocessed = Some(fx.path("out/demo.yaml"));
    run_in(fx.dir.path(), args).unwrap();
    assert!(fx.path("out/demo.yaml").exists());
    assert!(!fx.path("specs/demo.preprocessed.yaml").exists());
}

#[test]
fn manifest_edits_keep_authored_dependencies() {
    let text = "[package]\nname = \"p\"\n\n[dependencies]\nserde = \"1\"\n";
    let out = ensure_deps(text, &DetectedDeps::default()).unwrap();
    assert!(out.contains("serde = \"1\""));
    assert!(out.contains("aomi-sdk = { workspace = true }"));
    assert_eq!(out, ensure_deps(&out, &DetectedDeps::default()).unwrap());
}
