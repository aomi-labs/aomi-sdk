use std::fmt::Write;

use crate::client::Mode;

use super::{Op, ParamKind, ResponseSummary};

pub fn cargo_toml(platform: &str, mode: Mode) -> String {
    let client = match mode {
        Mode::Shared => {
            format!("{platform}-client = {{ path = \"../../crates/clients/{platform}\" }}\n")
        }
        // The generated module's own deps are added by `ensure_deps`.
        Mode::AppLocal => String::new(),
    };
    format!(
        r#"[package]
name = "{platform}"
version = "0.1.0"
edition = "2024"
license = "MIT"
publish = false

[lib]
crate-type = ["cdylib"]

[dependencies]
aomi-sdk = {{ workspace = true }}
{client}schemars = "1.0.4"
serde = {{ version = "1.0", features = ["derive"] }}
serde_json = "1.0"
"#
    )
}

/// The package manifest: the hosts the operations call, each with a
/// conservative pace to tune.
pub fn aomi_toml(platform: &str, ops: &[Op]) -> String {
    let mut hosts: Vec<&str> = ops.iter().map(|o| host_of(&o.server_url)).collect();
    hosts.sort_unstable();
    hosts.dedup();
    let list = hosts
        .iter()
        .map(|h| format!("\"{h}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let mut out = format!(
        "[package]\nname = \"{platform}\"\ndescription = \"{platform} API tools generated from its OpenAPI spec.\"\n# icon = \"icon.png\"\ncontract = 1\n\n[network]\nhosts = [{list}]\n"
    );
    for host in hosts {
        let _ = write!(
            out,
            "\n[[network.pace]]\nhost = \"{host}\"\nrate = \"1/1s\"\nburst = 1\n"
        );
    }
    out
}

fn host_of(url: &str) -> &str {
    let rest = url.split_once("://").map_or(url, |(_, rest)| rest);
    rest.split(['/', ':']).next().unwrap_or(rest)
}

pub fn lib_rs(platform: &str, ops: &[Op], mode: Mode) -> String {
    let tools = ops
        .iter()
        .map(|o| format!("tool::{}", o.tool_marker))
        .collect::<Vec<_>>()
        .join(", ");
    let client = match mode {
        Mode::AppLocal => "#[allow(clippy::all, dead_code, unused_imports)]\nmod client;\n",
        Mode::Shared => "",
    };
    format!(
        "//! Generated by `aomi-build gen-tool {platform}`. Tool definitions are\n\
         //! starting points: edit `src/tool.rs` to refine names, descriptions and\n\
         //! response shaping.\n\n\
         {client}mod tool;\n\n\
         aomi_sdk::package!({tools});\n"
    )
}

pub fn tool_rs(platform: &str, ops: &[Op], mode: Mode) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "//! Generated by `aomi-build gen-tool {platform}`. Each tool is a stub:\n\
         //! the wiring works (args -> client call -> JSON outcome) but review tool\n\
         //! names, descriptions and response shaping. The host injects credentials\n\
         //! from the slots declared in `aomi.toml`; tools never see a key."
    );
    let _ = writeln!(out);
    let client = match mode {
        Mode::Shared => format!("{}_client", platform.replace('-', "_")),
        Mode::AppLocal => "crate::client".to_string(),
    };
    let _ = writeln!(out, "use {client}::Client as GenClient;");
    let _ = writeln!(out, "#[allow(unused_imports)]\nuse {client}::types::*;");
    let _ = writeln!(out, "use aomi_sdk::{{Ctx, Outcome, Result, Tool, err}};");
    let _ = writeln!(out, "use schemars::JsonSchema;");
    let _ = writeln!(out, "use serde::Deserialize;");
    let _ = writeln!(out);
    for op in ops {
        emit_tool(&mut out, platform, op);
    }
    out
}

fn emit_tool(out: &mut String, platform: &str, op: &Op) {
    let method = crate::spec_load::snake_case(&op.operation_id);
    let args_struct = format!("{}Args", op.tool_marker);
    let summary = op
        .summary
        .clone()
        .or_else(|| op.description.clone())
        .unwrap_or_else(|| format!("{} {}", op.method.to_uppercase(), op.path));
    let description = sanitize_one_liner(&summary);

    let _ = writeln!(out, "// {} {}", op.method.to_uppercase(), op.path);
    let _ = writeln!(out, "pub(crate) struct {};", op.tool_marker);
    let _ = writeln!(out);
    let _ = writeln!(out, "#[derive(Debug, Deserialize, JsonSchema)]");
    let _ = writeln!(out, "pub(crate) struct {args_struct} {{");
    for p in op.params.iter().filter(|p| !p.is_auth) {
        if let Some(d) = &p.description {
            let _ = writeln!(out, "    /// {}", sanitize_one_liner(d));
        }
        if !p.required {
            let _ = writeln!(out, "    #[serde(default)]");
        }
        let ty = rust_type(p.kind);
        let _ = if p.required {
            writeln!(out, "    pub {}: {ty},", p.snake_name)
        } else {
            writeln!(out, "    pub {}: Option<{ty}>,", p.snake_name)
        };
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(out, "impl Tool for {} {{", op.tool_marker);
    let _ = writeln!(out, "    const NAME: &'static str = \"{method}\";");
    let _ = writeln!(
        out,
        "    const DESCRIPTION: &'static str = \"{description}\";"
    );
    let _ = writeln!(out, "    type Args = {args_struct};");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    async fn run(args: Self::Args, _ctx: &Ctx) -> Result<Outcome> {{"
    );
    let _ = writeln!(
        out,
        "        let client = GenClient::new(\"{}\");",
        op.server_url
    );
    let call_args: Vec<String> = op
        .params
        .iter()
        .map(|p| match (p.is_auth, p.required, p.kind) {
            (true, ..) => "None".to_string(),
            (_, true, ParamKind::String | ParamKind::Other) => {
                format!("args.{}.as_str()", p.snake_name)
            }
            (_, false, ParamKind::String | ParamKind::Other) => {
                format!("args.{}.as_deref()", p.snake_name)
            }
            _ => format!("args.{}", p.snake_name),
        })
        .collect();
    let _ = writeln!(out, "        let reply = client");
    let _ = writeln!(out, "            .{method}({})", call_args.join(", "));
    let _ = writeln!(out, "            .await");
    let _ = writeln!(
        out,
        "            .map_err(|e| err(\"request_failed\", format!(\"[{platform}] {method}: {{e}}\")))?;"
    );
    match &op.response_summary {
        ResponseSummary::Typed { rust_type } => {
            let _ = writeln!(
                out,
                "        // Reply: `{rust_type}` goes to the model as-is; drop fields it does not act on from the spec and regenerate."
            );
        }
        ResponseSummary::Loose => {
            let _ = writeln!(
                out,
                "        // Reply: loose JSON (`additionalProperties: true`); tighten the spec with `aomi-build tighten-spec`."
            );
        }
        ResponseSummary::Bytes => {
            let _ = writeln!(
                out,
                "        // Reply: bytes (non-JSON content type); decode and summarise as needed."
            );
        }
    }
    let _ = writeln!(out, "        Ok(Outcome::data(reply.into_inner()))");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
}

fn rust_type(k: ParamKind) -> &'static str {
    match k {
        ParamKind::String => "String",
        ParamKind::Int32 => "i32",
        ParamKind::Int64 => "i64",
        ParamKind::Number => "f64",
        ParamKind::Boolean => "bool",
        // EnumString shouldn't reach the renderer (op gets skipped earlier),
        // but fall back to String defensively.
        ParamKind::EnumString | ParamKind::Other => "String",
    }
}

fn sanitize_one_liner(s: &str) -> String {
    s.lines()
        .next()
        .unwrap_or("")
        .trim()
        .replace('"', "'")
        .replace('\\', "\\\\")
}
